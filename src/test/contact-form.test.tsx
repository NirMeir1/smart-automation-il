import { beforeEach, describe, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { ContactForm } from '@/components/contact-form'
import { inquirySuccess, privacyAcknowledgement, unavailableMessage } from '@/lib/inquiry'

const fetchMock = vi.fn()
beforeEach(() => { fetchMock.mockReset(); vi.stubGlobal('fetch', fetchMock) })
function fill(contact = '0502345678') {
  fireEvent.change(screen.getByLabelText('שם מלא *'), { target: { value: 'ישראל' } })
  fireEvent.change(screen.getByLabelText(contact.includes('@') ? 'אימייל' : 'טלפון'), { target: { value: contact } })
  fireEvent.change(screen.getByLabelText('אני פונה בתור *'), { target: { value: 'עסק' } })
  fireEvent.change(screen.getByLabelText('מה הייתם רוצים לפתור? *'), { target: { value: 'רוצה לשפר את התהליך' } })
  fireEvent.click(screen.getByRole('checkbox', { name: privacyAcknowledgement }))
}
describe('Contact form', () => {
  it('submits both contact methods and preserves optional fields', async () => {
    fetchMock.mockResolvedValue({ ok: true, json: async () => ({ success: true }) })
    render(<ContactForm enabled />); fill()
    fireEvent.change(screen.getByLabelText('אימייל'), { target: { value: 'person@example.test' } })
    fireEvent.change(screen.getByLabelText('אם רלוונטי — באילו כלים או מערכות אתם משתמשים היום?'), { target: { value: 'Sheets' } })
    fireEvent.click(screen.getByRole('button', { name: /שליחת הפנייה/ }))
    await screen.findByRole('heading', { name: inquirySuccess.title })
    expect(JSON.parse(fetchMock.mock.calls[0][1].body)).toMatchObject({ email: 'person@example.test', phone: '0502345678', systems: 'Sheets' })
  })
  it('links contact errors to editable fields and rejects an invalid supplied email', () => {
    render(<ContactForm enabled />); fill()
    fireEvent.change(screen.getByLabelText('אימייל'), { target: { value: 'bad' } })
    fireEvent.click(screen.getByRole('button', { name: /שליחת הפנייה/ }))
    expect(screen.getByRole('link', { name: 'יש להזין כתובת אימייל תקינה.' })).toHaveAttribute('href', '#email')
    expect(fetchMock).not.toHaveBeenCalled()
  })
  it('discloses missing configuration and disables collection/submission', () => {
    render(<ContactForm enabled={false} />)
    expect(screen.getByText(unavailableMessage)).toBeInTheDocument()
    expect(screen.getByRole('button', { name: /שליחת הפנייה/ })).toBeDisabled()
    expect(screen.getByLabelText('שם מלא *')).toBeDisabled()
    expect(fetchMock).not.toHaveBeenCalled()
  })
  it('provides accessible client validation before submitting', () => {
    render(<ContactForm enabled />)
    fireEvent.click(screen.getByRole('checkbox', { name: privacyAcknowledgement }))
    fireEvent.click(screen.getByRole('button', { name: /שליחת הפנייה/ }))
    expect(screen.getByRole('alert')).toHaveFocus()
    expect(screen.getByLabelText('שם מלא *')).toHaveAttribute('aria-invalid', 'true')
    expect(screen.getByRole('link', { name: 'יש למלא שם מלא.' })).toHaveAttribute('href', '#name')
    expect(fetchMock).not.toHaveBeenCalled()
  })
  it('keeps submission disabled without consent, including programmatic form submission', () => {
    render(<ContactForm enabled />)
    const button = screen.getByRole('button', { name: /שליחת הפנייה/ })
    expect(button).toBeDisabled()
    fireEvent.submit(button.closest('form')!)
    expect(fetchMock).not.toHaveBeenCalled()
    fill()
    expect(button).toBeEnabled()
    fireEvent.click(screen.getByRole('checkbox', { name: privacyAcknowledgement }))
    expect(button).toBeDisabled()
    fireEvent.submit(button.closest('form')!)
    expect(fetchMock).not.toHaveBeenCalled()
  })
  it('rejects the reported overlong phone on blur and submit, then clears the error when corrected', () => {
    render(<ContactForm enabled />); fill('05238349823983')
    const phone = screen.getByLabelText('טלפון')
    fireEvent.blur(phone)
    expect(phone).toHaveAttribute('aria-invalid', 'true')
    expect(screen.getByText(/יש להזין מספר טלפון תקין, כולל קידומת/, { selector: '#phone-error' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: /שליחת הפנייה/ }))
    expect(fetchMock).not.toHaveBeenCalled()
    fireEvent.change(phone, { target: { value: '0522345678' } })
    expect(phone).toHaveAttribute('aria-invalid', 'false')
    expect(screen.queryByText(/יש להזין מספר טלפון תקין, כולל קידומת/)).not.toBeInTheDocument()
  })
  it('shows email and name errors on blur without prematurely submitting', () => {
    render(<ContactForm enabled />)
    const email = screen.getByLabelText('אימייל')
    fireEvent.change(email, { target: { value: 'person..name@example.com' } })
    fireEvent.blur(email)
    expect(email).toHaveAttribute('aria-invalid', 'true')
    const name = screen.getByLabelText('שם מלא *')
    fireEvent.change(name, { target: { value: '12345' } })
    fireEvent.blur(name)
    expect(name).toHaveAttribute('aria-invalid', 'true')
    expect(fetchMock).not.toHaveBeenCalled()
  })
  it.each(['0502345678', 'person@example.test'])('confirms only backend success for %s', async contact => {
    fetchMock.mockResolvedValue({ ok: true, json: async () => ({ success: true }) })
    render(<ContactForm enabled />); fill(contact)
    fireEvent.click(screen.getByRole('button', { name: /שליחת הפנייה/ }))
    await screen.findByRole('heading', { name: inquirySuccess.title })
    await waitFor(() => expect(screen.getByRole('status')).toHaveFocus())
    expect(screen.getByText(inquirySuccess.body)).toBeInTheDocument()
    const sent = JSON.parse(fetchMock.mock.calls[0][1].body)
    expect(sent[contact.includes('@') ? 'email' : 'phone']).toBe(contact); expect(sent.privacy).toBe(true)
    expect(sent).not.toHaveProperty('marketingConsent')
    expect(localStorage.setItem).not.toHaveBeenCalled()
  })
  it('retains entered data and shows failure on server or network error', async () => {
    fetchMock.mockResolvedValueOnce({ ok: false, json: async () => ({ error: 'לא נשלח' }) }).mockRejectedValueOnce(new Error('network'))
    render(<ContactForm enabled />); fill()
    fireEvent.click(screen.getByRole('button', { name: /שליחת הפנייה/ }))
    expect(await screen.findByText('לא נשלח')).toBeInTheDocument()
    expect(screen.getByLabelText('שם מלא *')).toHaveValue('ישראל')
    expect(screen.queryByText(inquirySuccess.title)).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: /שליחת הפנייה/ }))
    await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('לא התקבל אישור שליחה'))
  })
  it('keeps the same retry ID until the visitor changes the inquiry', async () => {
    fetchMock.mockResolvedValue({ ok: false, json: async () => ({ error: 'לא נשלח' }) })
    render(<ContactForm enabled />); fill()
    fireEvent.click(screen.getByRole('button', { name: /שליחת הפנייה/ }))
    await screen.findByRole('alert')
    fireEvent.click(screen.getByRole('button', { name: /שליחת הפנייה/ }))
    await waitFor(() => expect(fetchMock).toHaveBeenCalledTimes(2))
    expect(JSON.parse(fetchMock.mock.calls[0][1].body).submissionId).toBe(JSON.parse(fetchMock.mock.calls[1][1].body).submissionId)
    await waitFor(() => expect(screen.getByRole('button', { name: /שליחת הפנייה/ })).not.toBeDisabled())
    fireEvent.change(screen.getByLabelText('מה הייתם רוצים לפתור? *'), { target: { value: 'בעיה אחרת' } })
    fireEvent.click(screen.getByRole('button', { name: /שליחת הפנייה/ }))
    await waitFor(() => expect(fetchMock).toHaveBeenCalledTimes(3))
    expect(JSON.parse(fetchMock.mock.calls[2][1].body).submissionId).not.toBe(JSON.parse(fetchMock.mock.calls[0][1].body).submissionId)
  })
  it('retains the audience intent received from the server', () => {
    render(<ContactForm enabled initialIntent="idea" />)
    expect(screen.getByLabelText('אני פונה בתור *')).toHaveValue('יזם/ת')
  })
  it('disables repeat submit while awaiting confirmation and never trusts an empty 200 response', async () => {
    let resolve!: (value: unknown) => void
    fetchMock.mockReturnValue(new Promise(r => { resolve = r }))
    render(<ContactForm enabled />); fill()
    fireEvent.click(screen.getByRole('button', { name: /שליחת הפנייה/ }))
    expect(screen.getByRole('button', { name: /שולחים/ })).toBeDisabled()
    resolve({ ok: true, json: async () => ({}) })
    await screen.findByRole('alert')
    expect(screen.queryByText(inquirySuccess.title)).not.toBeInTheDocument()
  })
  it('offers all three meeting formats, optional budget/tools and links the actual privacy page', () => {
    render(<ContactForm enabled />)
    expect(screen.getAllByRole('radio')).toHaveLength(3)
    expect(screen.getByRole('radio', { name: 'אין העדפה' })).toBeChecked()
    expect(screen.getByRole('link', { name: 'מדיניות הפרטיות' })).toHaveAttribute('href', '/legal/privacy')
    expect(screen.getByLabelText('יש טווח השקעה משוער שחשוב לדעת?')).not.toBeRequired()
  })
})
